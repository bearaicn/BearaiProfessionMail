-- 时光服维护者补充：选矿／研磨等泛用技能无法从固定配方消耗表完整反推。
-- 与旧世／无限服隔离，避免扩展专业和材料污染其他客户端。
local function add(items, professions)
    for _, itemID in ipairs(items) do
        local rule = ns.MaterialRules[itemID] or {}
        ns.MaterialRules[itemID] = rule
        for _, profession in ipairs(professions) do rule[profession] = true end
    end
end
